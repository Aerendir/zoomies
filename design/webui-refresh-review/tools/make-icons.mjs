// Generate public/icons.js: the Lucide glyphs the concepts draw, as data.
//
// The mockups are plain HTML and cannot import a Svelte component, but a
// concept that drew its own approximation of an icon would be judged on a shape
// the product does not have. So each glyph is read from the installed
// @lucide/svelte package (ISC), and the GitHub mark from the product's own
// GithubMark.svelte, and written out once. To use another icon, add its name
// below and run this again.
//
//   node design/webui-refresh-review/tools/make-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const web = resolve(fileURLToPath(new URL('.', import.meta.url)), '../../../web');
const lucide = resolve(web, 'node_modules/@lucide/svelte');

const WANTED = [
  'activity', 'arrow-left', 'arrow-right', 'arrow-up-right', 'ban', 'bell', 'boxes', 'cable',
  'chart-no-axes-combined', 'check', 'chevron-down', 'chevron-left', 'chevron-right',
  'circle-alert', 'circle-check', 'circle-question-mark', 'clock', 'cloud', 'compass', 'copy', 'cpu',
  'database', 'download', 'ellipsis', 'external-link', 'eye', 'eye-off', 'file-text', 'funnel',
  'flag', 'gauge', 'git-branch', 'git-pull-request-arrow', 'globe', 'hard-drive', 'clock-fading',
  'house', 'info', 'key-round', 'laptop', 'layers', 'layout-dashboard', 'link', 'list-ordered',
  'lock', 'log-out', 'memory-stick', 'menu', 'moon', 'pause', 'pencil', 'play', 'plug', 'plus',
  'refresh-cw', 'rocket', 'scan-line', 'scroll-text', 'search', 'server', 'settings',
  'shield-check', 'sparkles', 'sun', 'tag', 'terminal', 'trash', 'triangle-alert', 'trophy',
  'user', 'user-round', 'users', 'workflow', 'wrench', 'x', 'zap',
];

function nodesOf(name) {
  const source = readFileSync(resolve(lucide, 'dist/icons', `${name}.svelte`), 'utf8');
  const match = /const iconData = (\{.*\});/.exec(source);
  if (!match) throw new Error(`cannot find the icon data in ${name}.svelte`);
  return JSON.parse(match[1]).node;
}

const githubPath = /<path\s+d="([^"]+)"/.exec(
  readFileSync(resolve(web, 'src/lib/icons/GithubMark.svelte'), 'utf8'),
)?.[1];
if (!githubPath) throw new Error('cannot find the GitHub mark path in GithubMark.svelte');

const version = JSON.parse(readFileSync(resolve(lucide, 'package.json'), 'utf8')).version;
const nodes = Object.fromEntries(WANTED.map((name) => [name, nodesOf(name)]));

const output = `// Generated by tools/make-icons.mjs from @lucide/svelte ${version} (ISC) and the
// product's GithubMark.svelte. Do not edit; add a name to the generator instead.

const NODES = ${JSON.stringify(nodes, null, 1)};

const GITHUB_PATH = ${JSON.stringify(githubPath)};

/** Every glyph this module can draw. */
export const NAMES = Object.keys(NODES);

const attributes = (map) =>
  Object.entries(map)
    .map(([key, value]) => \`\${key}="\${String(value).replaceAll('"', '&quot;')}"\`)
    .join(' ');

/** A Lucide glyph as a decorative inline SVG. A name that was not generated throws. */
export function icon(name, size = 16) {
  const nodes = NODES[name];
  if (!nodes) throw new Error(\`no icon called "\${name}"; add it to tools/make-icons.mjs\`);
  const inner = nodes.map(([tag, attrs]) => \`<\${tag} \${attributes(attrs)}/>\`).join('');
  return (
    \`<svg class="icon" xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" \` +
    \`viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" \` +
    \`stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">\${inner}</svg>\`
  );
}

/** The GitHub mark: filled, as the product draws it, since Lucide has no brand icons. */
export function githubMark(size = 16) {
  return (
    \`<svg class="icon" xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" \` +
    \`viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">\` +
    \`<path d="\${GITHUB_PATH}"/></svg>\`
  );
}
`;

writeFileSync(resolve(fileURLToPath(new URL('../public/icons.js', import.meta.url))), output);
console.log(`Wrote ${WANTED.length} Lucide icons and the GitHub mark to public/icons.js`);
