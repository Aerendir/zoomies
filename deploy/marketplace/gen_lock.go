//go:build ignore

// Command gen_lock resolves every image reference this deployment package
// depends on to the digest it points at today, and writes images.lock.
//
// A marketplace artefact promises a particular build, and a tag cannot keep
// that promise: tags move, and the person deploying six months from now has no
// way to tell that the controller they got is not the one that was tested. The
// lock file is the record that makes the promise checkable -- it is what an
// operator, an auditor or a provider's security review compares a running
// deployment against.
//
// The catalogue in internal/naming is the source for which runner variants
// exist, so a new operating system is picked up here by adding its row there
// rather than by remembering this file.
//
// Run it from the repository root after changing the release in release.env:
//
//	make marketplace-lock
//
// It needs network access to the registry and nothing else: the manifests it
// asks for are public, and it pulls no layers.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/eyupio/zoomies/internal/naming"
	"github.com/eyupio/zoomies/internal/registry"
)

const (
	dir      = "deploy/marketplace"
	lockFile = "images.lock"
	envFile  = "release.env"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen_lock:", err)
		os.Exit(1)
	}
}

func run() error {
	env, err := readEnv(filepath.Join(dir, envFile))
	if err != nil {
		return err
	}
	release := env["ZOOMIES_RELEASE"]
	if release == "" {
		return fmt.Errorf("%s names no ZOOMIES_RELEASE", envFile)
	}

	refs := []string{stripDigest(env["ZOOMIES_CONTROLLER_IMAGE"])}
	for _, key := range []string{"ZOOMIES_PROXY_IMAGE", "ZOOMIES_TUNNEL_IMAGE"} {
		if ref := stripDigest(env[key]); ref != "" {
			refs = append(refs, ref)
		}
	}
	for _, img := range naming.Images() {
		tag := img.Tag() + "-" + release
		refs = append(refs,
			env["ZOOMIES_RUNNER_REPO"]+":"+tag,
			env["ZOOMIES_RUNNER_DOCKER_REPO"]+":"+tag,
		)
	}
	sort.Strings(refs)

	resolver := registry.Resolver{}
	digests := make(map[string]string, len(refs))
	width := 0
	for _, ref := range refs {
		d, err := resolver.Resolve(ref)
		if err != nil {
			return fmt.Errorf("resolving %s: %w", ref, err)
		}
		digests[ref] = d
		if len(ref) > width {
			width = len(ref)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# Every image %s deploys, and the digest its tag resolved to.\n", release)
	b.WriteString("#\n")
	b.WriteString("# Generated by `make marketplace-lock`; do not edit. Each line is one image\n")
	b.WriteString("# reference and the digest it pointed at when this release was locked, so a\n")
	b.WriteString("# deployment can be audited against what was published rather than against\n")
	b.WriteString("# whatever the tag means today.\n#\n")
	b.WriteString("# The runner images are here for that audit, not because the bootstrap picks\n")
	b.WriteString("# one: a controller resolves its runners from its own build tag, so pinning\n")
	b.WriteString("# the controller pins every line below with it.\n\n")
	for _, ref := range refs {
		fmt.Fprintf(&b, "%-*s  %s\n", width, ref, digests[ref])
	}
	return os.WriteFile(filepath.Join(dir, lockFile), []byte(b.String()), 0o644)
}

// readEnv reads the KEY=value lines of release.env. It is deliberately not a
// shell: the file is sourced by the bootstrap, so anything that needed quoting
// or expansion to be understood here would be a trap there.
func readEnv(path string) (map[string]string, error) {
	raw, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			return nil, fmt.Errorf("%s: %q is not KEY=value", path, line)
		}
		out[strings.TrimSpace(k)] = strings.TrimSpace(v)
	}
	return out, nil
}

// stripDigest turns a tag-and-digest reference back into the tag alone, which
// is the question the registry answers.
func stripDigest(ref string) string {
	if i := strings.Index(ref, "@"); i >= 0 {
		return ref[:i]
	}
	return ref
}
